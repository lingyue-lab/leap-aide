#!/usr/bin/env python3
"""brief.py — write the closing brief as a file.

The loop's last act is a summary: the plan, what changed, what the tests
said, what the review decided, and every ruling the supervisor took along the
way. Delivered as chat prose that summary is lost the moment the context
compacts; delivered as a file it survives, and the human reviewer can read it
next to the pull request.

    python3 brief.py [--out PATH] [--workspace DIR]

Reads <workspace>/.leap-aide/supervise/state.json and renders the brief from
it — no network access, no re-derivation of the loop's history. Prints one
JSON object with the path it wrote.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import supervise_state  # noqa: E402  (local sibling module)

DEFAULT_OUT_REL = Path(".leap-aide") / "supervise" / "brief.md"


def _die(message: str) -> int:
    print(json.dumps({"error": message}, indent=2), file=sys.stderr)
    return 1


def _safe_out(root: Path, requested: str) -> Path:
    """Resolve `requested` under `root`, rejecting anything that escapes it."""
    root = root.resolve()
    candidate = Path(requested)
    if not candidate.is_absolute():
        candidate = root / requested
    candidate = candidate.resolve()
    if candidate != root and root not in candidate.parents:
        raise ValueError(f"path escapes the workspace: {requested}")
    return candidate


def _stamp(ts: float) -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(ts))


def render(state: dict) -> str:
    """Render the state file as the supervisor's closing brief."""
    lines: list[str] = []
    lines.append("# Closing brief")
    lines.append("")
    lines.append(f"- Issue: {state.get('issue') or '(unknown)'}")
    if state.get("repo"):
        lines.append(f"- Repository: {state['repo']}")
    lines.append(f"- Status: {state.get('status') or 'unknown'}")
    lines.append(f"- Phase reached: {state.get('phase') or 'unknown'}")
    branch = state.get("branch")
    if branch:
        lines.append(f"- Branch: {branch}")
    pr = state.get("pr") or {}
    if pr.get("number"):
        label = pr.get("url") or f"#{pr['number']}"
        lines.append(f"- Pull request: {label}")
    lines.append(f"- Last updated: {_stamp(float(state.get('updated_at') or 0))}")
    lines.append("")

    lines.append("## Attempts")
    lines.append("")
    lines.append("| Phase | Attempts | Max |")
    lines.append("|---|---|---|")
    attempts = state.get("attempts") or {}
    max_attempts = int(state.get("max_attempts") or supervise_state.DEFAULT_MAX_ATTEMPTS)
    for phase in supervise_state.PHASES:
        lines.append(f"| {phase} | {attempts.get(phase, 0)} | {max_attempts} |")
    lines.append("")

    lines.append("## Rulings I made")
    lines.append("")
    rulings = state.get("rulings") or []
    if rulings:
        for i, ruling in enumerate(rulings, 1):
            what = str(ruling.get("what") or "").strip()
            why = str(ruling.get("why") or "").strip()
            cost = str(ruling.get("cost") or "").strip()
            parts = [what, why] if why else [what]
            if cost:
                parts.append(cost)
            phase = ruling.get("phase")
            suffix = f" _(phase: {phase})_" if phase else ""
            lines.append(f"{i}. Ruling: " + " — ".join(parts) + suffix)
    else:
        lines.append("None.")
    lines.append("")

    lines.append("## Event history")
    lines.append("")
    history = state.get("history") or []
    if history:
        for entry in history[-50:]:
            event = entry.get("event", "?")
            when = _stamp(float(entry.get("at") or 0))
            detail = ", ".join(
                f"{k}={v}" for k, v in entry.items()
                if k not in ("event", "at") and v not in ("", None)
            )
            lines.append(f"- `{when}` **{event}**" + (f" — {detail}" if detail else ""))
    else:
        lines.append("None.")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("Generated by `brief.py` from `.leap-aide/supervise/state.json`.")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="brief.py",
        description="Write the supervise loop's closing brief as a file.",
    )
    parser.add_argument("--out", default=str(DEFAULT_OUT_REL),
                        help=f"output path, relative to the workspace "
                             f"(default: {DEFAULT_OUT_REL.as_posix()})")
    parser.add_argument("--workspace", default=None,
                        help="workspace root (defaults to $HERMES_WORKSPACE or the cwd)")
    args = parser.parse_args(argv)

    workspace = supervise_state.workspace_root(args.workspace)
    state = supervise_state.load_state(workspace)
    if state is None:
        return _die(f"no supervise state at {supervise_state.state_path(workspace)}; "
                    "run `init` first")

    try:
        out = _safe_out(workspace, args.out)
    except ValueError as exc:
        return _die(str(exc))

    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(out.suffix + ".tmp")
    tmp.write_text(render(state), encoding="utf-8")
    tmp.replace(out)

    print(json.dumps({
        "path": str(out),
        "status": state.get("status"),
        "phase": state.get("phase"),
        "rulings": len(state.get("rulings") or []),
        "history": len(state.get("history") or []),
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
